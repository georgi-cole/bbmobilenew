const MESSAGE_CATALOGS: Record<AppLanguage, PartialMessageCatalog> = {
  'en-US': EN_US_MESSAGES,
  'en-GB': EN_GB_MESSAGES,
  'fr-FR': FR_FR_MESSAGES,
  'it-IT': IT_IT_MESSAGES,
  'es-ES': ES_ES_MESSAGES,
  'pt-PT': PT_PT_MESSAGES,
  'de-DE': DE_DE_MESSAGES,
  'zh-CN': ZH_CN_MESSAGES,
  'bg-BG': BG_BG_MESSAGES,
  'ru-RU': RU_RU_MESSAGES,
  'uk-UA': UK_UA_MESSAGES,
  'tr-TR': TR_TR_MESSAGES,
}

export function translate(
  language: AppLanguage,
  key: TranslationKey,
  params?: TranslationParams
): string {
  const template = MESSAGE_CATALOGS[language][key] ?? EN_US_MESSAGES[key]
  if (!params) return template

  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, token: string) =>
    Object.hasOwn(params, token) ? String(params[token]) : match
  )
}
